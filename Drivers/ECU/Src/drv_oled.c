/* ----------------------------------------------------------------
 * Inicialização dos pinos I2C como GPIO saída push-pull
 * ---------------------------------------------------------------- */
static void _gpio_init(void)
{
    /* Clock GPIOC — bit 2 em RCC_AHB2ENR */
    volatile uint32_t *RCC_AHB2ENR = (volatile uint32_t *)0x4002104CUL;
    *RCC_AHB2ENR |= (1U << 2U);

    /* PC0 = SCL: output push-pull, very high speed, sem pull */
    OLED_SCL_PORT->MODER  = (OLED_SCL_PORT->MODER  & ~(3U << (OLED_SCL_PIN * 2U)))
                           | (1U << (OLED_SCL_PIN * 2U));
    OLED_SCL_PORT->OTYPER &= ~(1U << OLED_SCL_PIN);
    OLED_SCL_PORT->OSPEEDR|=  (3U << (OLED_SCL_PIN * 2U));
    OLED_SCL_PORT->PUPDR  &= ~(3U << (OLED_SCL_PIN * 2U));

    /* PC1 = SDA: output push-pull, very high speed, sem pull */
    OLED_SDA_PORT->MODER  = (OLED_SDA_PORT->MODER  & ~(3U << (OLED_SDA_PIN * 2U)))
                           | (1U << (OLED_SDA_PIN * 2U));
    OLED_SDA_PORT->OTYPER &= ~(1U << OLED_SDA_PIN);
    OLED_SDA_PORT->OSPEEDR|=  (3U << (OLED_SDA_PIN * 2U));
    OLED_SDA_PORT->PUPDR  &= ~(3U << (OLED_SDA_PIN * 2U));

    _SCL_HI(); _SDA_HI();
    _delay_us(10U);
}

/* ----------------------------------------------------------------
 * API pública
 * ---------------------------------------------------------------- */
void DRV_OLED_Init(void)
{
    _gpio_init();
    _delay_us(10000U);  /* aguarda OLED estabilizar após power-on */

    static const uint8_t init_seq[] = {
        0xAE,        /* Display OFF                  */
        0xD5, 0x80,  /* Clock divide / oscilador     */
        0xA8, 0x3F,  /* Multiplex ratio = 64-1       */
        0xD3, 0x00,  /* Display offset = 0           */
        0x40,        /* Start line = 0               */
        0x8D, 0x14,  /* Charge pump ON               */
        0x20, 0x00,  /* Horizontal addressing mode   */
        0xA1,        /* Segment remap col127→SEG0    */
        0xC8,        /* COM output scan reverso      */
        0xDA, 0x12,  /* COM pins configuration       */
        0x81, 0xCF,  /* Contraste = 207              */
        0xD9, 0xF1,  /* Pre-charge period            */
        0xDB, 0x40,  /* VCOMH deselect level         */
        0xA4,        /* Output segue RAM             */
        0xA6,        /* Normal (não invertido)       */
        0x2E,        /* Desativa scroll              */
        0xAF,        /* Display ON                   */
    };

    for (uint8_t i = 0U; i < (uint8_t)sizeof(init_seq); i++) {
        _oled_cmd(init_seq[i]);
    }

    DRV_OLED_Clear();
    DRV_OLED_Flush();
}

void DRV_OLED_Clear(void)
{
    memset(s_fb, 0x00, sizeof(s_fb));
}

void DRV_OLED_Print(uint8_t col_px, uint8_t row, const char *str)
{
    if (!str || row >= OLED_PAGES) return;
    uint8_t x = col_px;

    while (*str && x < OLED_WIDTH) {
        uint8_t ch = (uint8_t)*str++;
        if (ch < 0x20U || ch > 0x7FU) ch = 0x20U;
        const uint8_t *glyph = s_font6x8[ch - 0x20U];
        for (uint8_t c = 0U; c < OLED_CHAR_W && x < OLED_WIDTH; c++, x++) {
            s_fb[row][x] = glyph[c];
        }
    }
}

void DRV_OLED_InvertRow(uint8_t row)
{
    if (row >= OLED_PAGES) return;
    for (uint8_t c = 0U; c < OLED_WIDTH; c++) {
        s_fb[row][c] ^= 0xFFU;
    }
}

void DRV_OLED_Flush(void)
{
    /* Define janela: colunas 0-127, páginas 0-7 */
    _oled_cmd(0x21U); _oled_cmd(0x00U); _oled_cmd(0x7FU);
    _oled_cmd(0x22U); _oled_cmd(0x00U); _oled_cmd(0x07U);

    /* Envia cada página em uma transação I2C */
    for (uint8_t page = 0U; page < OLED_PAGES; page++) {
        _oled_write(0x40U, s_fb[page], OLED_WIDTH);  /* D/C#=1 → dados */
    }
}
