/**
 * drv_oled.c — Driver OLED SSD1315/SSD1306 128×64, I2C software (bit-bang).
 *
 * Bare-metal, sem HAL. Acesso direto aos registradores GPIO.
 * Pinos: OLED_SCL=PC0, OLED_SDA=PC1 (definidos em pinout.h).
 *
 * DRV_OLED_Init() reconfigura PC0 e PC1 como GPIO saída push-pull,
 * independentemente de como estavam configurados (ADC analógico em modo ECU).
 *
 * Delay de I2C: usa DWT_CYCCNT (habilitado em main.c/_dwt_init antes de Init).
 * Velocidade: ~100 kHz (delay de 5 µs por borda).
 */

#include "drv_oled.h"
#include "pinout.h"
#include "ecu_config.h"
#include <string.h>

/* ----------------------------------------------------------------
 * Delay preciso via DWT_CYCCNT
 * Requer que main.c/_dwt_init() tenha sido chamado antes.
 * ---------------------------------------------------------------- */
#define DWT_CYCCNT_REG  (*((volatile uint32_t *)0xE0001004UL))

static void _delay_us(uint32_t us)
{
    uint32_t start = DWT_CYCCNT_REG;
    uint32_t wait  = us * (ECU_SYSCLOCK_HZ / 1000000UL);
    while ((DWT_CYCCNT_REG - start) < wait) {}
}

/* ----------------------------------------------------------------
 * Software I2C — primitivas
 * ---------------------------------------------------------------- */
#define _SCL_HI()   GPIO_SET(OLED_SCL_PORT, OLED_SCL_PIN)
#define _SCL_LO()   GPIO_CLR(OLED_SCL_PORT, OLED_SCL_PIN)
#define _SDA_HI()   GPIO_SET(OLED_SDA_PORT, OLED_SDA_PIN)
#define _SDA_LO()   GPIO_CLR(OLED_SDA_PORT, OLED_SDA_PIN)

static void _i2c_start(void)
{
    _SDA_HI(); _SCL_HI(); _delay_us(5U);
    _SDA_LO();             _delay_us(5U);  /* SDA↓ com SCL↑ = START */
    _SCL_LO();             _delay_us(5U);
}

static void _i2c_stop(void)
{
    _SDA_LO(); _SCL_HI(); _delay_us(5U);
    _SDA_HI();             _delay_us(5U);  /* SDA↑ com SCL↑ = STOP */
}

static void _i2c_write_byte(uint8_t b)
{
    for (int8_t i = 7; i >= 0; i--) {
        if (b & (1U << i)) { _SDA_HI(); } else { _SDA_LO(); }
        _delay_us(2U);
        _SCL_HI(); _delay_us(5U);
        _SCL_LO(); _delay_us(3U);
    }
    /* Pulso de clock para ACK (não lemos — master-only) */
    _SDA_HI(); _delay_us(2U);
    _SCL_HI(); _delay_us(5U);
    _SCL_LO(); _delay_us(3U);
}

/* Envia ctrl + buf em uma transação I2C */
static void _oled_write(uint8_t ctrl, const uint8_t *buf, uint16_t len)
{
    _i2c_start();
    _i2c_write_byte((uint8_t)(OLED_I2C_ADDR << 1U));
    _i2c_write_byte(ctrl);
    for (uint16_t i = 0U; i < len; i++) {
        _i2c_write_byte(buf[i]);
    }
    _i2c_stop();
}

static void _oled_cmd(uint8_t cmd)
{
    _oled_write(0x00U, &cmd, 1U);  /* D/C# = 0 → comando */
}

